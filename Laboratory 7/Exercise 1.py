ENZYMES = [
    {"name": "EcoRI",   "site": "GAATTC", "cut_offset": 1, "cleavage": "G^AATTC"},
    {"name": "BamHI",   "site": "GGATCC", "cut_offset": 1, "cleavage": "G^GATCC"},
    {"name": "HindIII", "site": "AAGCTT", "cut_offset": 1, "cleavage": "A^AGCTT"},
]


def find_cut_positions(seq, enzyme):
    site, off = enzyme["site"], enzyme["cut_offset"]
    return [m.start() + off for m in re.finditer(f"(?={site})", seq)]


def digest(seq, cut_positions):
    cuts = sorted(set(cut_positions))
    bounds = [0] + cuts + [len(seq)]
    return [seq[bounds[i]:bounds[i + 1]] for i in range(len(bounds) - 1)]


def main():
    seq = SEQUENCE.upper()
    print(f"Length : {len(seq)} bp\n")

    for enz in ENZYMES:
        cuts = find_cut_positions(seq, enz)
        frags = digest(seq, cuts)
        print(f"{enz['name']}  recognition: {enz['site']}  cleavage: {enz['cleavage']}")
        print(f"  sites found   : {len(cuts)}")
        print(f"  cut positions : {cuts}")
        print(f"  fragments     : {[len(f) for f in frags]}\n")


if __name__ == "__main__":
    main()